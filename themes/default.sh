# Default theme — maps palette colors to UI roles
# Each THM_ROLE_* variable defines what palette color a component uses.
# Override any of these in a custom theme to remap colors without changing the palette.

# Module accents (pill background colors)
THM_ROLE_SESSION="$THM_YELLOW"
THM_ROLE_DIRECTORY="$THM_BLUE"
THM_ROLE_SSH="$THM_MAGENTA"
THM_ROLE_APP="$THM_GREEN"
THM_ROLE_DATETIME="$THM_GRAY"
THM_ROLE_BATTERY="$THM_ORANGE"
THM_ROLE_WEATHER="$THM_CYAN"

# Module foregrounds (pill text colors)
THM_ROLE_SESSION_FG="$THM_BG_BASE"
THM_ROLE_MODULE_FG="$THM_BG_SURFACE"

# Window styling
THM_ROLE_ACTIVE_BG="$THM_BLUE"
THM_ROLE_ACTIVE_FG="$THM_BG_BASE"
THM_ROLE_INACTIVE_BG="$THM_BG_SURFACE"
THM_ROLE_INACTIVE_FG="$THM_FG_TEXT"
